-- Bootstrap the lazy.nvim plugin manager.
-- On first launch it clones lazy.nvim itself. No other plugins are installed:
-- add your own specs under lua/plugins/ and they get imported automatically.
local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
if not (vim.uv or vim.loop).fs_stat(lazypath) then
    local lazyrepo = "https://github.com/folke/lazy.nvim.git"
    local out = vim.fn.system({
        "git",
        "clone",
        "--filter=blob:none",
        "--branch=stable",
        lazyrepo,
        lazypath,
    })
    if vim.v.shell_error ~= 0 then
        vim.api.nvim_echo({
            { "Failed to clone lazy.nvim:\n", "ErrorMsg" },
            { out, "WarningMsg" },
        }, true, {})
        vim.fn.getchar()
        os.exit(1)
    end
end
vim.opt.rtp:prepend(lazypath)

require("lazy").setup({
    spec = {
        -- Import every plugin spec from lua/plugins/.
        { import = "plugins" },
    },
    checker = { enabled = false }, -- don't auto-check for plugin updates
})
